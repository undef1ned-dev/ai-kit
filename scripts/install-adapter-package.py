ROOT = Path(__file__).resolve().parent.parent
TEMPLATE_MEMORY_INDEX = ROOT / "base" / "memory" / "INDEX.md"

ROOT_FILES_BLOCKED_IN_CONSUMER = {
    "AIKIT.md",
    "CLAUDE.md",
    "CONTINUE_AIKIT_MAINTAINER.md",
    "PRODUCT.md",
    "RUNTIME.md",
}
# Earlier AIKit versions installed a maintainer handoff prompt; an update removes it
MAINTAINER_PROMPT_NAME = "CONTINUE_AIKIT_MAINTAINER.md"
AGENTS_MD_BEGIN = "<!-- BEGIN AIKIT — managed by AIKit installer, edits inside this block are overwritten -->"
AGENTS_MD_END = "<!-- END AIKIT -->"
RULES_FILE_REFERENCE = re.compile(r"(?<![\w/.-])CLAUDE\.md")
# Generated by earlier AIKit versions in places no runtime reads
LEGACY_GENERATED_PATHS = (
    Path(".codex") / "commands",
    Path(".codex") / "skills",
    Path(".aikit") / "runtime-graph.json",
    Path(".codex") / "runtime-graph.json",
    Path(".opencode") / "runtime-graph.json",
    Path(".aikit") / "runtime-operating-protocol.md",
    Path(".aikit") / "runtime-continuation-contract.md",
    Path(".aikit") / "runtime-tools.json",
    Path(".aikit") / "mcp-tool-plane.json",
)


def load_builder_module():
    path = ROOT / "scripts" / "build-adapter-package.py"
    spec = importlib.util.spec_from_file_location("aikit_build_adapter_package", path)
    if spec is None or spec.loader is None:
        raise SystemExit(f"Unable to load builder module from {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Install AIKit adapter bundle into a workspace")
    parser.add_argument("adapter", help="adapter directory name under adapters/")
    selector = parser.add_mutually_exclusive_group(required=True)
    selector.add_argument("--profile", help="profile or profile1+profile2")
    selector.add_argument("--preset", help="preset name under presets/")
    parser.add_argument("--pack", action="append", default=[], help="optional pack name, can be repeated")
    parser.add_argument("--commit", choices=project_settings.COMMIT_MODES, help="ask for the commit message or commit by the rules")
    parser.add_argument(
        "--workspace",
        required=True,
        help="target workspace where runtime files should be installed",
    )
    return parser.parse_args()


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, data: dict) -> None:
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def parse_frontmatter(text: str) -> dict[str, object]:
    match = re.match(r"^---\s*\n(.*?)\n---\s*\n?", text, re.DOTALL)
    if not match:
        return {}

    result: dict[str, object] = {}
    for line in match.group(1).splitlines():
        line = line.rstrip()
        if not line or line.lstrip().startswith("#"):
            continue
        kv = re.match(r"^([\w][\w-]*):\s*(.*)", line)
        if not kv:
            continue
        key, raw_value = kv.group(1), kv.group(2).strip()
        if raw_value.startswith("[") and raw_value.endswith("]"):
            inner = raw_value[1:-1]
            result[key] = [item.strip().strip('"').strip("'") for item in inner.split(",") if item.strip()]
            continue
        if len(raw_value) >= 2 and raw_value[0] == raw_value[-1] and raw_value[0] in {'"', "'"}:
            result[key] = raw_value[1:-1]
            continue
        result[key] = raw_value
    return result


def strip_leading_frontmatter(text: str) -> str:
    return re.sub(r"^---\s*\n.*?\n---\s*\n?", "", text, count=1, flags=re.DOTALL)


def normalize_markdown_frontmatter_yaml(text: str) -> str:
    match = re.match(r"^---\s*\n(.*?)\n---(\s*\n.*|\s*)$", text, re.DOTALL)
    if not match:
        return text

    raw_frontmatter = match.group(1)
    remainder = match.group(2)
    normalized_lines: list[str] = []

    for line in raw_frontmatter.splitlines():
        stripped = line.rstrip()
        if not stripped or stripped.lstrip().startswith("#"):
            normalized_lines.append(stripped)
            continue

        kv = re.match(r"^([\w][\w-]*):\s*(.*)$", stripped)
        if not kv:
            normalized_lines.append(stripped)
            continue

        key, raw_value = kv.group(1), kv.group(2).strip()
        if not raw_value:
            normalized_lines.append(f"{key}: \"\"")
            continue

        if raw_value.startswith("[") and raw_value.endswith("]"):
            normalized_lines.append(f"{key}: {raw_value}")
            continue

        if len(raw_value) >= 2 and raw_value[0] == raw_value[-1] and raw_value[0] in {'"', "'"}:
            normalized_lines.append(f"{key}: {raw_value}")
            continue

        if raw_value in {"true", "false", "null"} or re.fullmatch(r"-?\d+(?:\.\d+)?", raw_value):
            normalized_lines.append(f"{key}: {raw_value}")
            continue

        normalized_lines.append(f"{key}: {json.dumps(raw_value, ensure_ascii=False)}")

    return "---\n" + "\n".join(normalized_lines) + "\n---" + remainder


def resolve_profiles_and_packs(profile_arg: str | None, preset_name: str | None, packs: list[str]) -> tuple[str, list[str]]:
    profiles_arg = profile_arg
    resolved_packs = list(packs)
    if preset_name:
        preset = resolve_preset(preset_name)
        profiles_arg = preset["profiles_arg"]
        resolved_packs = [*preset["packs"], *resolved_packs]
    if not profiles_arg:
        raise SystemExit("Either --profile or --preset must resolve to a profile selection")
    return profiles_arg, resolved_packs


def sync_bundle(bundle_root: Path, workspace: Path, skip_rel_paths: list[Path] | None = None) -> None:
    skip_paths = _unique_rel_paths(skip_rel_paths or [])

    def is_skipped(relative_path: Path) -> bool:
        normalized = Path(relative_path.as_posix().strip("/"))
        for skip_path in skip_paths:
            if normalized == skip_path or normalized.is_relative_to(skip_path):
                return True
        return False

    def copy_recursive(source: Path, destination: Path, relative_path: Path) -> None:
        if is_skipped(relative_path):
            return
        if source.is_dir():
            destination.mkdir(parents=True, exist_ok=True)
            for child in sorted(source.iterdir()):
                child_relative = relative_path / child.name if relative_path.parts else Path(child.name)
                copy_recursive(child, destination / child.name, child_relative)
            return
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)

    for item in sorted(bundle_root.iterdir()):
        copy_recursive(item, workspace / item.name, Path(item.name))


def _unique_rel_paths(paths: list[Path]) -> list[Path]:
    unique: list[Path] = []
    seen: set[str] = set()
    for path in paths:
        key = path.as_posix().strip("/")
        if not key or key in seen:
            continue
        seen.add(key)
        unique.append(Path(key))
    return unique


def consumer_memory_paths(adapter: dict) -> list[Path]:
    adapter_memory_path = Path(str(adapter.get("memory_path", ".aikit/memory")).strip())
    return _unique_rel_paths(
        [
            Path(".aikit/memory"),
            adapter_memory_path,
        ]
    )


def ensure_consumer_memory_dirs(workspace: Path, rel_paths: list[Path]) -> None:
    for rel_path in rel_paths:
        target = workspace / rel_path
        if target.exists() and not target.is_dir():
            target.unlink()
        target.mkdir(parents=True, exist_ok=True)
        ensure_memory_structure(target, TEMPLATE_MEMORY_INDEX)


def remove_path(path: Path) -> None:
    if path.is_dir():
        shutil.rmtree(path)
    elif path.exists():
        path.unlink()


def strip_maintainer_entrypoints(path: Path) -> None:
    if not path.exists():
        return
    data = read_json(path)
    entrypoints = data.get("entrypoints")
    if not isinstance(entrypoints, list):
        return
    filtered = [
        entry
        for entry in entrypoints
        if not (
            isinstance(entry, dict)
            and (
                entry.get("name") == "continue-maintainer"
                or MAINTAINER_PROMPT_NAME in str(entry.get("path", ""))
            )
        )
    ]
    if len(filtered) != len(entrypoints):
        data["entrypoints"] = filtered
        write_json(path, data)


def strip_consumer_manifest_fields(path: Path) -> None:
    if not path.exists():
        return
    data = read_json(path)
    changed = False

    generated_artifacts = data.get("generated_artifacts")
    if isinstance(generated_artifacts, list):
        filtered_artifacts = [
            artifact
            for artifact in generated_artifacts
            if isinstance(artifact, str)
            and Path(artifact).name not in ROOT_FILES_BLOCKED_IN_CONSUMER
            and MAINTAINER_PROMPT_NAME not in artifact
        ]
        if filtered_artifacts != generated_artifacts:
            data["generated_artifacts"] = filtered_artifacts
            changed = True

    runtime_entrypoints = data.get("runtime_entrypoints")
    if isinstance(runtime_entrypoints, list):
        filtered_entrypoints = [
            entry
            for entry in runtime_entrypoints
            if not (
                isinstance(entry, dict)
                and (
                    entry.get("name") == "continue-maintainer"
                    or MAINTAINER_PROMPT_NAME in str(entry.get("path", ""))
                )
            )
        ]
        if filtered_entrypoints != runtime_entrypoints:
            data["runtime_entrypoints"] = filtered_entrypoints
            changed = True

    if data.get("continuation_prompt"):
        data["continuation_prompt"] = ""
        changed = True

    if changed:
        write_json(path, data)


def kit_relative_files(bundle_root: Path) -> set[str]:
    """Workspace-relative paths the package ships; everything else in the project belongs to the team."""
    return {path.relative_to(bundle_root).as_posix() for path in bundle_root.rglob("*") if path.is_file()}


def render_codex_custom_agents(workspace: Path, kit_files: set[str]) -> list[dict[str, str]]:
    agents_root = workspace / ".codex" / "agents"
    if not agents_root.exists():
        return []

    rendered: list[dict[str, str]] = []
    for agent_file in sorted(agents_root.glob("*.md")):
        # A team's own markdown agent stays as it is: only the kit's agents are converted
        if f".codex/agents/{agent_file.name}" not in kit_files:
            continue
        content = read_text(agent_file)
        metadata = parse_frontmatter(content)
        role_name = str(metadata.get("name") or agent_file.stem).strip()
        if not role_name:
            role_name = agent_file.stem
        description = str(metadata.get("description") or f"AIKit role {role_name}").strip()
        developer_instructions = strip_leading_frontmatter(content).strip()
        # Backslashes first, otherwise TOML multiline basic strings reject sequences like "\d" in agent prompts
        developer_instructions = developer_instructions.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
        toml_lines = [
            f"name = {json.dumps(role_name, ensure_ascii=False)}",
            f"description = {json.dumps(description, ensure_ascii=False)}",
            'developer_instructions = """',
            developer_instructions,
            '"""',
            "",
        ]
        toml_path = agents_root / f"{agent_file.stem}.toml"
        write_text(toml_path, "\n".join(toml_lines))
        # Codex loads only *.toml agents; the markdown source stays in .aikit/agents
        agent_file.unlink()
        rendered.append(
            {
                "name": role_name,
                "description": description,
                "config_path": f"agents/{toml_path.name}",
            }
        )

    stale_config_root = workspace / ".codex" / "agent-configs"
    if stale_config_root.exists():
        shutil.rmtree(stale_config_root)

    return rendered


def prepare_codex_workspace_surface(workspace: Path, kit_files: set[str]) -> None:
    render_codex_custom_agents(workspace, kit_files)


def remove_previous_native_paths(workspace: Path) -> None:
    """Remove files the previous AIKit install put outside .aikit/, so a changed preset leaves no stale skills or agents."""
    manifest_path = workspace / ".aikit" / "package.manifest.json"
    previous = read_json(manifest_path).get("native_paths", []) if manifest_path.exists() else []
    workspace_root = workspace.resolve()
    for rel_path in [*previous, *LEGACY_GENERATED_PATHS]:
        target = (workspace / rel_path).resolve()
        if target.is_relative_to(workspace_root) and target != workspace_root:
            remove_path(target)


def remove_legacy_claude_commands(workspace: Path, bundle_root: Path) -> None:
    """Earlier versions installed skills as .claude/commands/<name>.md; only kit-named files are removed."""
    commands_dir = workspace / ".claude" / "commands"
    if not commands_dir.is_dir():
        return
    for skill_file in (bundle_root / ".aikit" / "skills").glob("*/SKILL.md"):
        remove_path(commands_dir / f"{skill_file.parent.name}.md")
    if not any(commands_dir.iterdir()):
        commands_dir.rmdir()


def render_agents_md_block(profiles: list[str]) -> str:
    chunks = [
        AGENTS_MD_BEGIN,
        "# AIKit — правила проекта",
        "",
        "Скиллы AIKit — в `.agents/skills/`, агенты — в `.codex/agents/` (Codex) и `.opencode/agents/` (OpenCode),",
        "память проекта — в `.aikit/memory/`.",
        "Правила ниже написаны в синтаксисе Claude Code: `/name` — это скилл `name` из `.agents/skills/`",
        "(в Codex вызывается как `$name`, в OpenCode — по имени; оба подхватывают скиллы и автоматически по описанию).",
        "",
        (ROOT / "base" / "CLAUDE.md").read_text(encoding="utf-8").strip(),
    ]
    for profile_name in profiles:
        profile_rules = ROOT / "profiles" / profile_name / "CLAUDE.md"
        if profile_rules.exists():
            chunks.extend(["", "---", "", profile_rules.read_text(encoding="utf-8").strip()])
    chunks.append(AGENTS_MD_END)
    return "\n".join(chunks) + "\n"


def merge_agents_md(workspace: Path, profiles: list[str]) -> None:
    """AGENTS.md is the project rules file for Codex and OpenCode; user content outside the AIKit block is kept."""
    agents_md = workspace / "AGENTS.md"
    block = render_agents_md_block(profiles)
    if not agents_md.exists():
        write_text(agents_md, block)
        return
    original = read_text(agents_md)
    pattern = re.compile(rf"{re.escape(AGENTS_MD_BEGIN)}.*?{re.escape(AGENTS_MD_END)}\n?", re.DOTALL)
    if pattern.search(original):
        updated = pattern.sub(lambda _: block, original)
    else:
        updated = original.rstrip() + "\n\n" + block
    write_text(agents_md, updated)


def rewrite_text_file(path: Path, replacements: dict[str, str]) -> None:
    text = read_text(path)
    updated = text
    for old, new in replacements.items():
        updated = updated.replace(old, new)
    if updated != text:
        write_text(path, updated)


def apply_consumer_workspace_policy(adapter: dict, workspace: Path) -> None:
    blocked_root_files = set(ROOT_FILES_BLOCKED_IN_CONSUMER)
    if str(adapter.get("runtime", "")).strip() == "claude":
        blocked_root_files.discard("CLAUDE.md")

    for file_name in blocked_root_files:
        remove_path(workspace / file_name)

    runtime = str(adapter.get("runtime", "")).strip()
    if runtime:
        remove_path(workspace / f".{runtime}" / MAINTAINER_PROMPT_NAME)
        strip_maintainer_entrypoints(workspace / f".{runtime}" / "entrypoints.json")

    strip_maintainer_entrypoints(workspace / ".aikit" / "runtime-entrypoints.json")
    strip_consumer_manifest_fields(workspace / ".aikit" / "adapter.manifest.json")
    strip_consumer_manifest_fields(workspace / ".aikit" / "package.manifest.json")


def point_rules_to_agents_md(text: str) -> str:
    """
    Codex and OpenCode read the project rules from AGENTS.md. A bare CLAUDE.md becomes AGENTS.md;
    lines that already name AGENTS.md and paths like profiles/<name>/CLAUDE.md (a file of the kit) stay.
    """
    return "\n".join(
        line if "AGENTS.md" in line else RULES_FILE_REFERENCE.sub("AGENTS.md", line) for line in text.split("\n")
    )


def rewrite_local_script_commands(workspace: Path, adapter: dict, kit_files: set[str]) -> None:
    runtime = str(adapter.get("runtime", "")).strip()
    if runtime not in {"codex", "opencode"}:
        return
    for agent_path in sorted((workspace / f".{runtime}" / "agents").glob("*.md")):
        if agent_path.relative_to(workspace).as_posix() in kit_files:
            text = read_text(agent_path)
            updated = point_rules_to_agents_md(text)
            if updated != text:
                write_text(agent_path, updated)

    replacements = {
        ".claude/agents/": f".{runtime}/agents/",
        ".claude/skills/": ".agents/skills/",
        ".claude/memory/": ".aikit/memory/",
        ".claude-config/": ".aikit-config/",
        "bash .claude-config/scripts/attach.sh <profile>": (
            "python3 .aikit-config/scripts/install-adapter-package.py "
            f"{runtime} --profile <profile> --workspace ."
        ),
    }
    for root in (workspace / f".{runtime}", workspace / ".agents" / "skills"):
        for markdown_path in sorted(root.rglob("*.md")):
            if markdown_path.relative_to(workspace).as_posix() in kit_files:
                rewrite_text_file(markdown_path, replacements)


def write_install_summary(adapter: dict, workspace: Path, bundle_root: Path) -> None:
    summary = [
        f"# AIKit Install Summary — {adapter['label']}",
        "",
        f"- Runtime: `{adapter['runtime']}`",
        f"- Status: `{adapter['status']}`",
        f"- Memory path: `{adapter['memory_path']}`",
        f"- Installed into: `{workspace}`",
        "",
        "## Next steps",
        "- Используй runtime-specific launcher внутри config root этого adapter.",
        "- Смотри `.aikit/runtime-entrypoints.json` как source of truth для runtime entrypoints этого workspace.",
        "- Смотри `.aikit/profiles.json`: агенты профилей по ролям, специалисты и команды проверки.",
    ]
    if adapter.get("runtime") == "codex":
        summary.extend(
            [
                "- Правила проекта — в `AGENTS.md`, скиллы — в `.agents/skills/` (вызов `$name` или автоматически), агенты — в `.codex/agents/*.toml`.",
                "- Чтобы Codex загрузил агентов из `.codex/`, проект должен быть отмечен как доверенный.",
                "- Хуки AIKit (`.codex/hooks.json`) заработают после одобрения в `/hooks`.",
            ]
        )
    summary.extend(
        [
            "",
            "## Source bundle",
            f"- Temporary build source: `{bundle_root}`",
        ]
    )
    (workspace / ".aikit" / "INSTALL.md").write_text("\n".join(summary) + "\n", encoding="utf-8")


def install_package(
    adapter_name: str,
    profiles_arg: str,
    packs: list[str],
    workspace: Path,
) -> dict:
    workspace.mkdir(parents=True, exist_ok=True)

    builder = load_builder_module()
    adapter_manifest_path = ROOT / "adapters" / adapter_name / "adapter.manifest.json"
    if not adapter_manifest_path.exists():
        raise SystemExit(f"Adapter '{adapter_name}' not found at {adapter_manifest_path.relative_to(ROOT)}")
    adapter = read_json(adapter_manifest_path)

    with tempfile.TemporaryDirectory(prefix=f"aikit-install-{adapter_name}-") as temp_dir:
        temp_root = Path(temp_dir)
        memory_paths = consumer_memory_paths(adapter)
        bundle_root = builder.build_package(
            adapter_name,
            profiles_arg,
            packs,
            temp_root,
        )
        kit_files = kit_relative_files(bundle_root)
        remove_previous_native_paths(workspace)
        remove_legacy_claude_commands(workspace, bundle_root)
        sync_bundle(bundle_root, workspace, skip_rel_paths=memory_paths)
        apply_consumer_workspace_policy(adapter, workspace)
        ensure_consumer_memory_dirs(workspace, memory_paths)
        rewrite_local_script_commands(workspace, adapter, kit_files)
        runtime = str(adapter.get("runtime", "")).strip()
        if runtime in {"codex", "opencode"}:
            merge_agents_md(workspace, [item.strip() for item in profiles_arg.split("+") if item.strip()])
        if runtime == "codex":
            prepare_codex_workspace_surface(workspace, kit_files)
        if runtime in {"codex", "opencode"}:
            agent_models.apply(runtime, workspace)
        if runtime in mcp_config.RUNTIMES:
            mcp_config.install(runtime, workspace, [item.strip() for item in profiles_arg.split("+") if item.strip()], packs)
        profile_contract.install(workspace, [item.strip() for item in profiles_arg.split("+") if item.strip()])
        if runtime in hooks_config.RUNTIMES:
            hooks_config.install(runtime, workspace)
        write_install_summary(adapter, workspace, bundle_root)

    return adapter


def main() -> int:
    args = parse_args()
    workspace = Path(args.workspace).resolve()
    profiles_arg, packs = resolve_profiles_and_packs(args.profile, args.preset, list(args.pack))
    install_package(args.adapter, profiles_arg, packs, workspace)
    project_settings.write(workspace, args.commit)

    print(f"Installed adapter package '{args.adapter}' into {workspace}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
